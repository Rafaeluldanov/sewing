/**
 * Юнит-тесты `buildRouteOperationRanks` — порядка колонок «Доски
 * движения тиража» и блоков «Экрана цеха». Без БД: чистая функция.
 *
 * Сценарии закрывают ровно то, ради чего порядок перестал браться из
 * справочного `Operation.sortOrder`:
 *   - 31.08.2026, заказ 02-00020: «Ф РАСПОШИВ ГОРЛОВИНЫ» (sortOrder
 *     420) и «ВТО ОКЛАД» (290) уезжали правее УПАКОВКИ (70), и тираж,
 *     идущий строго по маршруту, рисовался на доске зигзагом;
 *   - мультизаказная доска: индексы шагов РАЗНЫХ заказов несопоставимы,
 *     поэтому сортировка по min-индексу тоже даёт зигзаг;
 *   - повтор операции в маршруте (чередующиеся ОТК/ВТО) не должен
 *     превращаться в цикл;
 *   - противоречивые маршруты не имеют общего порядка — ни одна
 *     колонка при этом не должна пропасть.
 */
import { describe, expect, test } from 'vitest';
import {
  buildRouteOperationRanks,
  type RouteOperationOrderStep,
} from '../../apps/api/src/common/route-operation-order';

/** Компактный конструктор шага: заказ, индекс, операция, sortOrder. */
const step = (
  orderId: string,
  index: number,
  operationId: string,
  sortOrder: number,
): RouteOperationOrderStep => ({
  orderId,
  index,
  operationId,
  sortOrder,
  tieBreak: operationId,
});

/** Операции в порядке рангов — то, что реально увидит мастер. */
const ordered = (ranks: Map<string, number>): string[] =>
  [...ranks.entries()].sort((a, b) => a[1] - b[1]).map(([op]) => op);

describe('buildRouteOperationRanks', () => {
  test('02-00020: порядок берётся из маршрута, а не из справочника', () => {
    // Реальный снимок маршрута заказа 02-00020 (прод, 31.08.2026).
    // sortOrder намеренно «хвостовой» у ГОРЛОВИН и ВТО — именно он и
    // рисовал зигзаг ОВЕРЛОК → РАСПОШИВ → ОТК → УПАКОВКА → ВТО →
    // ГОРЛОВИНЫ.
    const steps = [
      step('A', 1, 'ОВЕРЛОК', 20),
      step('A', 2, 'РАСПОШИВ', 40),
      step('A', 3, 'ГОРЛОВИНЫ', 420),
      step('A', 4, 'ОТК', 50),
      step('A', 5, 'ВТО', 290),
      step('A', 6, 'УПАКОВКА', 70),
    ];

    expect(ordered(buildRouteOperationRanks(steps))).toEqual([
      'ОВЕРЛОК',
      'РАСПОШИВ',
      'ГОРЛОВИНЫ',
      'ОТК',
      'ВТО',
      'УПАКОВКА',
    ]);
  });

  test('порядок не зависит от того, как шаги легли во входном массиве', () => {
    // Стабильность между polling-tick'ами: на TV layout не должен
    // «прыгать» от того, в каком порядке Prisma вернула строки.
    const steps = [
      step('A', 5, 'ВТО', 290),
      step('A', 1, 'ОВЕРЛОК', 20),
      step('A', 6, 'УПАКОВКА', 70),
      step('A', 3, 'ГОРЛОВИНЫ', 420),
      step('A', 4, 'ОТК', 50),
      step('A', 2, 'РАСПОШИВ', 40),
    ];

    expect(ordered(buildRouteOperationRanks(steps))).toEqual([
      'ОВЕРЛОК',
      'РАСПОШИВ',
      'ГОРЛОВИНЫ',
      'ОТК',
      'ВТО',
      'УПАКОВКА',
    ]);
  });

  test('мультизаказная доска: индексы разных заказов не сравниваются', () => {
    // Заказ B знает, что ГОРЛОВИНЫ идут перед ОТК; заказ A про
    // ГОРЛОВИНЫ не знает вообще. Сортировка по min-индексу поставила бы
    // ОТК (index 2 у заказа A) перед ГОРЛОВИНАМИ (index 3 у заказа B) —
    // тот же зигзаг, только по другой причине.
    const steps = [
      step('A', 1, 'ОВЕРЛОК', 20),
      step('A', 2, 'ОТК', 50),
      step('B', 1, 'ОВЕРЛОК', 20),
      step('B', 2, 'РАСПОШИВ', 40),
      step('B', 3, 'ГОРЛОВИНЫ', 420),
      step('B', 4, 'ОТК', 50),
    ];

    expect(ordered(buildRouteOperationRanks(steps))).toEqual([
      'ОВЕРЛОК',
      'РАСПОШИВ',
      'ГОРЛОВИНЫ',
      'ОТК',
    ]);
  });

  test('повтор операции в маршруте не создаёт цикл', () => {
    // Чередующиеся ОТК/ВТО (см. project_route_repeated_operation).
    // Учитывается только первое вхождение — иначе ОТК→ВТО и ВТО→ОТК
    // дали бы встречные рёбра на ровном месте.
    const steps = [
      step('A', 1, 'ОВЕРЛОК', 20),
      step('A', 2, 'ОТК', 50),
      step('A', 3, 'ВТО', 290),
      step('A', 4, 'ОТК', 50),
      step('A', 5, 'УПАКОВКА', 70),
    ];

    expect(ordered(buildRouteOperationRanks(steps))).toEqual([
      'ОВЕРЛОК',
      'ОТК',
      'ВТО',
      'УПАКОВКА',
    ]);
  });

  test('противоречивые маршруты: ни одна колонка не теряется', () => {
    // Не гипотетика: на проде 31.08.2026 из 20 заказов в производстве
    // ровно один (02-00003) ведёт «Ф РАСПОШИВ» ПОСЛЕ «ВТО ОКЛАД»
    // (шаг 7 против шага 6), тогда как 02-00020 — до (шаг 2 против 5).
    // Общего линейного порядка для такой пары не существует. Падать и
    // выбрасывать колонки нельзя: на потерянной колонке пропадут
    // паспорта, а это ровно тот класс регресса («операция исчезла»),
    // который ловит defensive-инвариант в `buildSewingRoute`.
    const steps = [
      step('A', 2, 'РАСПОШИВ', 40),
      step('A', 5, 'ВТО', 290),
      step('B', 6, 'ВТО', 290),
      step('B', 7, 'РАСПОШИВ', 40),
    ];

    const ranks = buildRouteOperationRanks(steps);
    expect(ordered(ranks)).toHaveLength(2);
    expect(new Set(ranks.keys())).toEqual(new Set(['РАСПОШИВ', 'ВТО']));
  });

  test('несравнимые операции упорядочивает справочный sortOrder', () => {
    // Заказы не пересекаются, маршруты друг о друге ничего не говорят —
    // тай-брейком остаётся тот же порядок, что был до фикса.
    const steps = [
      step('A', 1, 'ПОЗЖЕ', 300),
      step('B', 1, 'РАНЬШЕ', 100),
    ];

    expect(ordered(buildRouteOperationRanks(steps))).toEqual([
      'РАНЬШЕ',
      'ПОЗЖЕ',
    ]);
  });

  test('пустой вход — пустой результат', () => {
    expect(buildRouteOperationRanks([]).size).toBe(0);
  });
});
