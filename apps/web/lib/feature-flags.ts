/**
 * Frontend feature-flag helpers.
 *
 * Раньше каждая страница админки писала свою проверку
 * `process.env.NEXT_PUBLIC_FEATURE_X === '1'`. Это было слишком хрупко:
 *   - если переменная не задана (например, на свежем `.env` без флагов),
 *     модуль автоматически прятался — даже когда страница, бекенд и DTO
 *     уже были выкачены в `main`. Менеджер открывал админку и не видел
 *     «Лекала», «Поставщиков», «Заказы поставщикам» и пр., хотя коде
 *     модули уже жили;
 *   - если кто-то выставлял `=true`, `=on`, `=yes` (что естественно для
 *     bash-флагов), пункт всё равно прятался;
 *   - чтобы временно скрыть модуль, приходилось *удалять* переменную
 *     или ставить заведомо мусорное значение, а это плохо для
 *     `.env.example` контракта.
 *
 * Договор `isFeatureEnabled` (используется во всём admin-UI):
 *   - `undefined` / пустая строка             → включено (default-on);
 *   - `'1' | 'true' | 'on' | 'yes' | 'enabled'` → включено;
 *   - `'0' | 'false' | 'off' | 'no' | 'disabled'` → выключено;
 *   - любое другое значение                   → включено
 *     (политика «default-on» — лучше показать новый модуль и получить
 *     обратную связь, чем тихо прятать готовую страницу).
 *
 * Backend всегда отвечает — флаг гейтит ТОЛЬКО UI-навигацию и
 * inline-блоки в карточках. См. комментарии в `admin-sidebar.tsx`,
 * `apps/web/app/admin/orders/[id]/page.tsx` и т.д.
 */

const DISABLED_VALUES = new Set(['0', 'false', 'off', 'no', 'disabled']);

/**
 * Возвращает `true`, если значение env не выглядит как «выключено».
 *
 * Пустое / неопределённое значение трактуется как «включено» — это
 * сознательная политика default-on для уже выкаченных модулей.
 */
export function isFeatureEnabled(value: string | undefined | null): boolean {
  if (value == null) return true;
  const trimmed = value.trim();
  if (trimmed === '') return true;
  return !DISABLED_VALUES.has(trimmed.toLowerCase());
}
