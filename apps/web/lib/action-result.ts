/**
 * Результат server action, который может «не получиться по делу»
 * (backend ответил 409/422 с человекочитаемым объяснением).
 *
 * ЗАЧЕМ ВОЗВРАЩАТЬ, А НЕ БРОСАТЬ. В production-сборке Next.js прячет
 * текст исключения, вылетевшего из server action, за заглушкой «An
 * error occurred in the Server Components render. The specific message
 * is omitted in production builds…» + digest. В dev текст виден, на
 * проде — нет, и менеджер вместо «к группе привязаны техкарты» получает
 * техническую ошибку. Возвращённое значение не редактируется, поэтому
 * все «ожидаемые» отказы едут сюда, а `throw` остаётся для настоящих
 * багов (их и правда незачем показывать пользователю).
 *
 * Форма совпадает с `ActionResult` в `app/constructor/actions.ts`
 * (появился раньше) — при следующей правке того файла его стоит
 * перевести на этот общий тип.
 */
export interface ActionResult {
  ok: boolean;
  /** Человекочитаемая причина отказа. Заполняется только при `ok: false`. */
  error?: string;
}
