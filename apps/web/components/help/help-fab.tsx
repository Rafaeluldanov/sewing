import Link from 'next/link';
import { BookOpen } from 'lucide-react';

/**
 * Кнопка «Справка» в столбике цеховых экранов (`/work`, `/qc`, `/wto`,
 * `/packing`) — единственный вход сотрудника с вопросом.
 *
 * Icon-only 40×40, как соседние кнопки тулбара: место на терминале
 * дорогое, а подпись даёт `aria-label`.
 *
 * Кнопка одна и ведёт в «Справку», а не в «Ассистента»: за этим окном
 * дальше встанут уровни ответа, и человек не должен выбирать, куда
 * идти с вопросом. Две заметные кнопки развели бы одинаковые вопросы
 * по разным дорогам — причём заметная кнопка ИИ утащила бы к модели то,
 * на что уже есть статья.
 */
export function HelpFab() {
  return (
    <Link
      href="/help"
      className="help-fab"
      aria-label="Справка"
      title="Справка"
    >
      <BookOpen size={20} strokeWidth={1.7} aria-hidden />
    </Link>
  );
}
