/**
 * Словарь подписей для швейного scan-flow (`SeamstressActivePanel` и
 * её дочерние карточки).
 *
 * Зачем понадобился. Панель писалась под швею, и её тексты говорят
 * «крой»: «Взять крой», «Сейчас у вас нет кроя в работе». Пока панель
 * жила только на `/work`, это было верно. Теперь её же рендерит
 * `/packing` в режиме некоробочной операции — упаковщик на «Распаковке»
 * (приёмка приходящего сырья, первый шаг маршрута, см.
 * `packing-terminal.tsx`). Ему кнопка «Взять крой» врёт: никакого кроя
 * на этом шаге ещё нет, он принимает поступивший товар.
 *
 * Поэтому подписи вынесены в параметр. Компонент по умолчанию берёт
 * `SEAMSTRESS_WORDING` — поведение `/work` не меняется ни на символ;
 * `/packing` передаёт `PACKING_INTAKE_WORDING`.
 *
 * Сюда попадают ТОЛЬКО тексты, зависящие от роли. Всё, что описывает
 * механику одинаково для всех («Сканируйте QR паспорта — откроется
 * проверка перед приёмом»), остаётся в компонентах: дублировать его в
 * каждом словаре — верный способ получить рассинхрон при первой правке.
 */
export interface WorkWording {
  /** Заголовок и aria-label карточки скана, когда на руках пусто. */
  take: string;
  /** То же, когда что-то уже взято, — «взять ещё одну единицу». */
  takeNext: string;
  /** Пустое состояние блока «Сейчас в работе». */
  emptyText: string;
}

/** Швея и помощник раскройщика на `/work` — исходные тексты. */
export const SEAMSTRESS_WORDING: WorkWording = {
  take: 'Взять крой',
  takeNext: 'Взять следующий крой',
  emptyText:
    'Сейчас у вас нет кроя в работе. Отсканируйте QR паспорта, чтобы взять крой.',
};

/**
 * Упаковщик на некоробочной операции («Распаковка» = приёмка сырья).
 *
 * Формулировки намеренно нейтральные — «паспорт», а не «крой» и не
 * «коробка»: операцию заводит клиент, и назвать её могут по-разному
 * («Распаковка», «Приёмка»), а сканирует он в любом случае паспорт.
 */
export const PACKING_INTAKE_WORDING: WorkWording = {
  take: 'Взять паспорт',
  takeNext: 'Взять следующий паспорт',
  emptyText:
    'Сейчас у вас нет паспортов в работе. Отсканируйте QR паспорта, чтобы взять его в работу.',
};
