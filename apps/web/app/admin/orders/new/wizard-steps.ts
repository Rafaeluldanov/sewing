/**
 * Конфигурация шагов мастера создания заказа (`/admin/orders/new`).
 *
 * Источник правды по списку шагов, их лейблам и подписям кнопки
 * «Далее». Отдельным файлом — по тем же причинам, что и
 * `order-view-tabs-config.ts` у карточки: конфиг нужен и клиентскому
 * компоненту мастера, и smoke-тестам, которые грепают исходники.
 *
 * Порядок шагов — это порядок РЕШЕНИЙ, а не порядок полей в базе:
 * сначала «чей заказ», потом «что шьём», и только потом всё, что от
 * изделия зависит. Прежняя одностраничная форма открывалась
 * подразделением, складом готовой продукции и политикой учёта
 * материалов в себестоимости — тремя редкими настройками (см. аудит
 * `docs/order-page-ui-recon.md` §4.1).
 *
 * `optional: true` — шаг можно пропустить кнопкой «Пропустить»:
 * маршрут и нанесение не мешают создать заказ и дозаполняются позже в
 * карточке. Клиент и изделие обязательны — без них черновик создавать
 * нечего; расцветки обязательны, потому что без плана по размерам
 * заказ не уйдёт в расчёт (`ORDER_ITEMS_REQUIRED`).
 *
 * Backend / DTO / Prisma не задействованы — это presentation-слой.
 */

export type WizardStepId =
  | 'client'
  | 'product'
  | 'colorways'
  | 'route'
  | 'applications'
  | 'review';

/**
 * Состояние шага в степпере.
 *
 * `blocked` — шаг недоступен структурно, а не «ещё не дошли»: в ветке
 * «Отправить конструктору» лекала ещё нет, поэтому у расцветок,
 * маршрута и нанесения нет ни размеров, ни техкарты. Показываем это
 * замком и подписью «после лекала», а не притворяемся, что шаг
 * доступен.
 */
export type WizardStepState =
  | 'done'
  | 'current'
  | 'pending'
  | 'skipped'
  | 'blocked';

export interface WizardStepConfig {
  id: WizardStepId;
  /** Короткий лейбл в степпере. */
  label: string;
  /** Заголовок панели шага — вопрос, на который отвечает шаг. */
  heading: string;
  /** Подпись главной кнопки перехода. */
  nextLabel: string;
  /** Шаг можно пропустить. */
  optional?: boolean;
}

