import { CutterShelfPanel } from './shelf-panel';
import { requireActiveCutterShift } from '../require-shift';

export const dynamic = 'force-dynamic';

/**
 * Вкладка «Стеллаж» кабинета раскройщика (`/cutter/shelf`) — третья из
 * трёх вкладок верхнего уровня (Раскрой · Выпуск · Стеллаж, макет
 * `docs/mockups/cutter-passport-release-mockup.html` §«Стеллаж»).
 *
 * Что делает: размещение уже выпущенного кроя в ячейку стеллажа.
 * Сценарий целиком реализован раньше для помощника раскройщика
 * (`docs/flows.md §F3b`) и переиспользуется здесь БЕЗ изменений:
 * скан QR ячейки → подтверждение (код + срез содержимого) → сессия
 * «сканируйте паспорта один за другим»; ячейка остаётся активной, пока
 * раскройщик не нажмёт «Готово». Одна ошибка размещения сессию не рвёт.
 *
 * Почему страница пустая: вся работа идёт внутри клиентского
 * `ShelfPlacementPanel` (камера + server actions), данных для
 * первичного рендера нет — ни одного запроса на сервере, поэтому и
 * fail-soft на `ApiRequestError` тут не нужен. `force-dynamic` стоит
 * ради согласованности раздела: `/cutter/*` целиком зависит от cookie
 * сессии (гуард и шапка в `cutter/layout.tsx`) и не должен попадать в
 * статический пререндер.
 *
 * Доступ: авторизацию и роль (`canSeeCutter`) проверяет
 * `cutter/layout.tsx`. Плюс гейт активной смены (`requireActiveCutterShift`)
 * — как на остальных вкладках: технически backend разрешил бы размещение и
 * без смены (`/passports/:id/place` требует только роль), но вкладки
 * рендерятся только в активной смене, и попасть сюда без неё можно лишь
 * прямой ссылкой. Пускать в этом состоянии работу без табеля
 * непоследовательно — отправляем на доску, где предложат начать смену.
 * Вкладки (`CutterTabs`) встраивает layout, страница их не рендерит.
 */
export default async function CutterShelfPage() {
  await requireActiveCutterShift();

  return (
    <div className="constructor-page">
      <h1 className="constructor-page__title">Стеллаж</h1>
      <p className="scan-card__hint cutter-shelf__hint">
        Отсканируйте ячейку, подтвердите её — затем сканируйте паспорта один
        за другим. Ячейка остаётся активной до конца смены.
      </p>
      <CutterShelfPanel />
    </div>
  );
}
