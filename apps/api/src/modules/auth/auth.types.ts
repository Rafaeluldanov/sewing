import type { Request } from 'express';

/**
 * Данные авторизованного пользователя, прикреплённые к запросу
 * после прохождения `AuthGuard` (см. `./auth.guard.ts`).
 *
 * Это минимально достаточный набор: id для бизнес-логики и роли для
 * RBAC-проверок без обращения в БД.
 *
 * ТИП РОЛЕЙ. С миграции «справочник ролей» (28.07.2026) роль — это
 * `string` (`AppRole.code`), а не Prisma-enum: роли заводятся из
 * админки. Коды 12 системных ролей не изменились, поэтому сравнения
 * вида `role === 'CUTTER'` по-прежнему валидны.
 */
export interface AuthPrincipal {
  employeeId: string;
  /**
   * ОСНОВНАЯ роль (`Employee.role`) — для категоризации и дефолтного
   * экрана. RBAC опирается на `roles` (см. ниже), а не на это поле.
   */
  role: string;
  /**
   * ЭФФЕКТИВНЫЙ набор ролей: назначенные сотруднику (`assignedRoles`)
   * плюс всё, что они наследуют по `AppRole.inherits` (транзитивно).
   * ИНВАРИАНТ: всегда содержит `role`. Именно на него смотрит
   * `AuthGuard` при проверке `@Roles(...)` — благодаря этому кастомная
   * роль «Технолог» с `inherits = ['SHOP_MANAGER']` проходит везде, где
   * пускают начальника цеха, без правки декораторов.
   */
  roles: string[];
  /**
   * НАЗНАЧЕННЫЙ набор (`Employee.roles`, без раскрытия наследования) —
   * то, что менеджер отметил галочками в карточке сотрудника.
   *
   * Нужен отдельно от `roles`, потому что «одно рабочее окно» считается
   * по нему: у сотрудника с единственной кастомной ролью раскрытый
   * набор содержал бы 2+ кода, и терминал ошибочно превратился бы в
   * полноценную навигацию.
   */
  assignedRoles: string[];
  /**
   * Текущая активная роль (`Employee.activeRole`) — последняя, на
   * которую переключились сканом рабочего места. `null` — берётся `role`.
   */
  activeRole: string | null;
  /**
   * Рабочий экран учётки, посчитанный по справочнику ролей
   * (`AppRole.workspace`). Отдаётся в `/api/auth/me`, чтобы веб не
   * держал собственную копию матрицы «роль → экран».
   */
  workspace: string;
  /** Прятать глобальную навигацию, `/` уводит на `workspace`. */
  singleWorkspace: boolean;
  /** Middleware не пускает на страницы вне `workspace`. */
  lockToWorkspace: boolean;
  /** Логин (`Employee.login`) для удобства логирования и UI. */
  login: string;
  /** ФИО для шапки UI. */
  fullName: string;
  /**
   * Вид субъекта. `MACHINE` — запрос пришёл по машинному токену (сервер-сервер,
   * интеграция с ERP), а не от человека с cookie. Поле ОПЦИОНАЛЬНОЕ намеренно:
   * `@CurrentUser()` используется в сотнях мест, и обязательное поле сломало бы их все.
   * Отсутствие поля = обычный человек, как было до 09.2026.
   */
  kind?: 'HUMAN' | 'MACHINE';
  /**
   * Скоупы машинного токена (`equipment:read`, `operations:write`, …). У человека
   * пусто: его права — роли. Проверяются в `AuthGuard` по `@MachineScopes(...)`,
   * DENY BY DEFAULT: маршрут без декоратора машине закрыт, сколько бы ролей у неё ни было.
   */
  scopes?: string[];
  /** Id записи `ServiceToken` — для аудита и отзыва «того самого» токена. */
  serviceTokenId?: string;
}

export interface RequestWithAuth extends Request {
  auth?: AuthPrincipal;
}
