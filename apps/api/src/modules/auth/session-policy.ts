/**
 * Политика жизни сессии: автовыход по бездействию и рубильник
 * «Завершить все сеансы».
 *
 * Зачем это вообще появилось. Сессия у нас stateless (HMAC-токен в
 * cookie, см. `./session.ts`) и живёт `JWT_EXPIRES_IN` от момента
 * входа — 12 часов по умолчанию. Терминал в цехе один на несколько
 * человек, кнопку «Выйти» после смены почти никто не жмёт, и следующий
 * садится под чужой учёткой: работа уходит не тому сотруднику. Ни
 * абсолютный TTL, ни logout-кнопка эту дыру не закрывали.
 *
 * Модель решения — «TTL cookie = окно бездействия»:
 *   - при входе cookie выпускается ровно на `sessionIdleTimeoutMinutes`;
 *   - каждое действие человека в интерфейсе продлевает её
 *     (`POST /api/auth/refresh`, зовёт клиентский сторож бездействия);
 *   - нет действий — токен протухает сам, без крона и без реестра
 *     сессий на сервере.
 *
 * Почему не «скользящее окно поверх длинного TTL»: тогда пришлось бы
 * хранить `lastSeenAt` на каждый запрос (лишняя запись в БД в горячем
 * пути) и всё равно верить клиенту в вопросе «была ли активность».
 *
 * Важно: продлевает сессию только ЯВНОЕ действие человека. Фоновые
 * опросы страниц (`/work`, доска цеха) идут обычными запросами и
 * `refresh` не зовут — иначе открытая вкладка держала бы сессию вечно
 * и вся настройка потеряла бы смысл.
 */

/**
 * Роли, которые автовыход не трогает никогда.
 *
 * `DISPLAY` — учётка большого монитора в цехе: экран висит на стене
 * сутками, «активность» на нём проявлять некому, а выкинутый на форму
 * логина монитор — это погашенная доска задач для всей смены.
 *
 * Список сознательно захардкожен, а не вынесен в настройку: это не
 * предпочтение владельца, а свойство самой учётки — за ней нет
 * человека.
 */
export const SESSION_IDLE_EXEMPT_ROLES = ['DISPLAY'] as const;

/** `0` — автовыход выключен (сессия живёт `JWT_EXPIRES_IN`). */
export const SESSION_IDLE_DISABLED = 0;

/**
 * Эффективное окно бездействия для конкретного набора ролей:
 * настройка организации минус исключения.
 *
 * Проверяем ВЕСЬ набор ролей, а не основную: если человеку выдали
 * `DISPLAY` вместе с рабочей ролью, учётка всё равно может висеть на
 * мониторе — выкидывать её нельзя.
 */
export function resolveIdleTimeoutMinutes(
  settingMinutes: number,
  roles: readonly string[],
): number {
  if (!Number.isFinite(settingMinutes) || settingMinutes <= 0) {
    return SESSION_IDLE_DISABLED;
  }
  const exempt = roles.some((r) =>
    (SESSION_IDLE_EXEMPT_ROLES as readonly string[]).includes(r),
  );
  return exempt ? SESSION_IDLE_DISABLED : Math.floor(settingMinutes);
}

/**
 * Значения политики, посчитанные один раз на запрос (в `AuthService`
 * кэшируются на несколько секунд — их читает КАЖДЫЙ авторизованный
 * запрос через `resolvePrincipal`).
 */
export interface SessionPolicy {
  /** Окно бездействия организации в минутах; `0` — выключено. */
  idleTimeoutMinutes: number;
  /**
   * Отсечка «Завершить все сеансы»: токены с `iat` строго раньше
   * недействительны. `null` — отсечки нет.
   */
  sessionsValidFrom: Date | null;
}

/** Политика, при которой ничего не ограничено (fallback на ошибке чтения). */
export const PERMISSIVE_SESSION_POLICY: SessionPolicy = {
  idleTimeoutMinutes: SESSION_IDLE_DISABLED,
  sessionsValidFrom: null,
};

/**
 * Отвергнута ли сессия рубильником «Завершить все сеансы».
 *
 * Сравниваем по `iat` (момент выпуска токена) в секундах — так же, как
 * он лежит в payload. Сессия, выпущенная РОВНО в момент отсечки,
 * считается живой: иначе новый вход сразу после нажатия кнопки
 * отвергался бы сам собой в пределах одной секунды.
 */
export function isSessionRevoked(
  issuedAtSeconds: number,
  sessionsValidFrom: Date | null,
): boolean {
  if (!sessionsValidFrom) return false;
  const cutoffSeconds = Math.floor(sessionsValidFrom.getTime() / 1000);
  return issuedAtSeconds < cutoffSeconds;
}
