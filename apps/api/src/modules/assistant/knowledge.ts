/** Поиск статей по запросу. Простой скоринг по вхождению слов. */
export function searchKnowledge(query: string, limit = 3): KnowledgeArticle[] {
  const q = query.toLowerCase();
  const words = q.split(/[^\p{L}\p{N}]+/u).filter((w) => w.length >= 3);

  const scored = KNOWLEDGE.map((article) => {
    let score = 0;
    for (const kw of article.keywords) {
      if (q.includes(kw)) score += 3;
    }
    for (const w of words) {
      if (article.title.toLowerCase().includes(w)) score += 2;
      if (article.body.toLowerCase().includes(w)) score += 1;
    }
    return { article, score };
  })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((s) => s.article);
}
