-- Автозавершение смен, забытых открытыми.
--
-- Зачем. Смена (`ShiftSession`) не связана с сессией и не закрывается
-- сама: человек уходит домой, не нажав «Завершить смену», и часы
-- продолжают идти. На проде на 31.08.2026 из 755 закрытых смен 429
-- длиннее 10 часов, 269 длиннее 16, 194 — дольше суток; рекорд 1643
-- часа (68 суток). Всё, что считается от времени в смене — загрузка,
-- «часы по дням», выработка в час — после такого недостоверно.
--
-- Правило настраивается: время суток по Москве и/или предельная
-- длительность смены. По умолчанию ВЫКЛЮЧЕНО — после миграции
-- поведение не меняется, пока владелец не задаст порог.

-- 1. Чем считать конец забытой смены.
CREATE TYPE "ShiftAutoCloseMode" AS ENUM ('AT_DEADLINE', 'LAST_ACTIVITY');

-- 2. Настройки организации (singleton).
ALTER TABLE "CompanySettings"
  ADD COLUMN "shiftAutoCloseTime" TEXT,
  ADD COLUMN "shiftMaxDurationHours" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN "shiftAutoCloseMode" "ShiftAutoCloseMode" NOT NULL DEFAULT 'LAST_ACTIVITY';

-- 3. Отметка «эту смену закрыла система».
--    Отдельно от `endedAt`: `endedAt` — конец РАБОТЫ (последняя отметка
--    сотрудника или порог), а здесь — когда об этом узнала система.
--    Исторические смены остаются с NULL: задним числом объявлять их
--    автозакрытыми нельзя, их закрывали люди.
ALTER TABLE "ShiftSession"
  ADD COLUMN "autoClosedAt" TIMESTAMP(3);
