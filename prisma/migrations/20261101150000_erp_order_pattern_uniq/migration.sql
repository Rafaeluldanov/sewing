-- Ключ идемпотентности отправки в цех — ПАРА «заказ покупателя ERP + лекало», а не заказ ERP.
--
-- Строки одного заказа покупателя разложены мастером по лекалам, и каждое лекало уезжает СВОИМ
-- заказом цеха (`docs/kb/sewing.md` §0.10: «все строки одного лекала уезжают одним заказом»).
-- Уникальность по одному `erpCustomerOrderId` отбивала бы вторую же группу: заказ, где есть и
-- футболка, и худи, стал бы неотправляемым — первая группа создавалась бы, вторая падала.
--
-- Пара уникальна по построению: мастер группирует строки по лекалу, двух групп с одним лекалом
-- в заказе не бывает. Повторная отправка той же группы по-прежнему отбивается (409), а строки
-- собственных заказов цеха (оба поля NULL) индекс не трогает — в Postgres NULL не равен NULL.

DROP INDEX IF EXISTS "Order_erpCustomerOrderId_key";

CREATE UNIQUE INDEX IF NOT EXISTS "Order_erp_customer_order_pattern_uniq"
  ON "Order" ("erpCustomerOrderId", "patternItemId");
