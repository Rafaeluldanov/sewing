-- СТОРОННИЕ УСЛУГИ НА ОПЕРАЦИИ ЗАКАЗА: «эту операцию (частью или целиком) делает подрядчик».
--
-- Просьба владельца 10.09.2026: «если указали, что делается на стороне — стоимость операции не
-- берём, считаем стоимость стороннего размещения; на самих операциях нужна отметка; в план-факте
-- достаточно метки».
--
-- Три колонки, все аддитивные:
--   OrderRouteStep.outsourced         — метка на шаге ЗАКАЗА (не на справочнике операции:
--                                       правка справочника поехала бы во все запущенные тиражи,
--                                       а подряд всегда про конкретный заказ);
--   OrderRouteStep.outsourcePriceRub  — цена размещения за ОДНО ИЗДЕЛИЕ (на сторону отдают тираж,
--                                       а не «часы»); NULL = цена не задана → в план идёт 0 и
--                                       warning, потому что молчаливый ноль читается как
--                                       «подряд бесплатный»;
--   OrderRouteStepSizeOverride.outsourcedQty — сколько штук размера отдано. Ни одного значения на
--                                       шаге ⇒ на стороне весь тираж операции; есть значения ⇒
--                                       ровно они, остальное цех считает своей расценкой.
--   Order.operationOutsourceCostPlanRub — расшифровка «в том числе размещение» внутри
--                                       operationCostPlanRub (само число остаётся ПОЛНЫМ планом
--                                       операций: иначе каждый потребитель складывал бы по-своему).
--
-- ⛔ ТОЛЬКО ДЕНЬГИ И МЕТКА. Плановое время, движение паспорта по маршруту, доска, гейты ОТК и
-- упаковки, начисление сдельной ЗП эти колонки не читают. Причина: по одной и той же операции
-- часть тиража цех обычно делает сам, поэтому «пропустить шаг» означало бы остановить паспорта
-- на упаковке (`packing.service.ts` считает число шагов QC/IRONING в маршруте) и потерять
-- незакрытую работу в диагностике.
--
-- ⛔ Деньги подряда в ERP (`sewing.outsource_line`, заказ поставщику) — ДРУГОЙ контур: там
-- документ и расчёты с контрагентом, здесь плановая себестоимость тиража. Фактическую
-- себестоимость сдачи цех по этим колонкам не меняет: факта по неотсканированной операции нет,
-- и ERP добавляет свой компонент подряда сама.

ALTER TABLE "OrderRouteStep"
  ADD COLUMN IF NOT EXISTS "outsourced"        BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "outsourcePriceRub" DECIMAL(12, 2);

ALTER TABLE "OrderRouteStepSizeOverride"
  ADD COLUMN IF NOT EXISTS "outsourcedQty" INTEGER;

ALTER TABLE "Order"
  ADD COLUMN IF NOT EXISTS "operationOutsourceCostPlanRub" DECIMAL(14, 2);
