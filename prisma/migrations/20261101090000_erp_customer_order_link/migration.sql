-- Прямой шов «заказ покупателя ERP → заказ цеха» (решение владельца 03.09.2026).
--
-- ЗАЧЕМ ПОЛЕ. Оно отличает заказ, рождённый в ERP, от собственного заказа цеха — и на этом
-- отличии стоят: сужение очереди выпуска готовой продукции (в неё попадают только заказы ERP,
-- поэтому чужие паспорта не получают необратимого ответа «не смогли»), идемпотентность отправки
-- (уникальность не даст завести второй заказ на тот же заказ ERP), резолв прихода, гард полноты
-- выпуска и запрет правки тиража в цехе — всё только для заказов ERP.
--
-- ЗАЧЕМ БЭКФИЛЛ. Имя заказчика переезжает в текстовое поле заказа: справочник клиентов цеха
-- выпиливается (решение владельца 03.09.2026 — единственный источник заказчиков это контрагенты
-- ERP). Сейчас `customer` пуст у ВСЕХ 119 заказов, а имя живёт только в карточке клиента —
-- без переноса история потеряет заказчика.

ALTER TABLE "Order" ADD COLUMN IF NOT EXISTS "erpCustomerOrderId" TEXT;
ALTER TABLE "Order" ADD COLUMN IF NOT EXISTS "erpCustomerOrderNumber" TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS "Order_erpCustomerOrderId_key"
  ON "Order" ("erpCustomerOrderId");

UPDATE "Order" o
SET "customer" = c."name"
FROM "Client" c
WHERE o."clientId" = c."id"
  AND (o."customer" IS NULL OR btrim(o."customer") = '');
