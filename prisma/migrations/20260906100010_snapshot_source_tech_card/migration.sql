-- ФАЗА 2 «Техкарта живёт в заказе, шаблон — снаружи».
--
-- Раньше снимок материалов пересобирался ИЗ ШАБЛОНА при каждом изменении
-- (правка расцветки, смена плана, старт расчёта): deleteMany + createMany.
-- Побочный эффект — правка шаблона в справочнике молча протекала в черновики.
--
-- Теперь пересборка перечитывает шаблон, только если техкарту группы сменили
-- (или строк ещё нет). Иначе пересчитываются лишь количества, а структура и
-- правки, сделанные в заказе, остаются. Признак «из какого шаблона
-- материализована группа» и есть эта колонка.
--
-- Без FK: шаблон могут удалить, а снимок обязан пережить это (та же логика,
-- что у `sourceTechCardLineId` с ON DELETE SET NULL).

ALTER TABLE "OrderMaterialRequirement" ADD COLUMN "sourceTechCardId" TEXT;

-- Бэкфилл: у существующих строк источник выводится из строки шаблона, от
-- которой они произошли. Без него ПЕРВАЯ же пересборка после деплоя увидела бы
-- sourceTechCardId = NULL, сочла группу неинициализированной и перечитала
-- шаблон — то есть ровно один раз повела бы себя по-старому. Не катастрофа,
-- но с бэкфиллом деплой становится строго no-op.
UPDATE "OrderMaterialRequirement" omr
SET "sourceTechCardId" = tcl."techCardId"
FROM "TechCardMaterialLine" tcl
WHERE tcl.id = omr."sourceTechCardLineId"
  AND omr."sourceTechCardId" IS NULL;
