-- Автовыход по бездействию + рубильник «Завершить все сеансы».
--
-- Зачем. Терминал в цехе один на несколько человек, «Выйти» после смены
-- не жмёт почти никто, и следующий работает под чужой учёткой. TTL
-- сессии абсолютный (12 часов от входа, `JWT_EXPIRES_IN`), поэтому от
-- этого он не спасал: смена кончилась, а сессия жива до утра.
--
-- Обе настройки singleton-ные (одна организация — одно правило) и
-- живут в `CompanySettings` рядом с прочими hardening-флагами.

-- 1. Окно бездействия в минутах. `0` = выключено, поведение прежнее.
--    Ненулевое значение = ровно столько живёт cookie сессии, а веб
--    продлевает её на действиях человека.
ALTER TABLE "CompanySettings"
  ADD COLUMN "sessionIdleTimeoutMinutes" INTEGER NOT NULL DEFAULT 0;

-- 2. Метка «все сессии, выпущенные раньше — недействительны».
--    Сессии stateless (HMAC-токен без реестра), поэтому «выгнать всех»
--    делается сравнением `SessionPayload.iat` с этой отметкой.
ALTER TABLE "CompanySettings"
  ADD COLUMN "sessionsValidFrom" TIMESTAMP(3);
