-- Достройка документа выпуска по уже закрытому заказу.
--
-- Заказы, закрытые ДО появления раздела, документа не получили: он рождается закрытием, а его
-- тогда не существовало. Все входы документа — исторические факты (упакованные паспорта,
-- списания, начисления, подкрой, события паспортов для разноски оклада), поэтому выпуск по ним
-- восстанавливается точно, а не выдумывается. Кнопка достройки и заводит такой документ.
--
-- ⛔ Отметка обязательна: номер достроенного документа несёт дату ЗАКРЫТИЯ заказа (иначе он
-- встал бы в сегодняшний суточный счётчик и порядок номеров разошёлся бы с порядком выпуска),
-- а сама строка появилась позже. Без `backfilledAt` это неотличимо от документа, оформленного
-- задним числом.

ALTER TABLE "ProductionDocument" ADD COLUMN "backfilledAt" TIMESTAMP(3);
