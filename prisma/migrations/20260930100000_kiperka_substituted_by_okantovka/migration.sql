-- Правило замены: ОКАНТОВКА ПЛЕЧЕВЫХ И ГОРЛОВИНЫ (code='11') засчитывает
-- КИПЕРКУ ФУТБОЛКА (code='03').
--
-- Инцидент 28.07.2026 (заказ O-20260510-0001 и ещё 7 заказов, 70 паспортов
-- / ~1100 шт). Цех перешёл на окантовку горловины (для неё заведён отдельный
-- шаблон маршрута «Футболка с окантовкой горловины», где на позиции киперки
-- стоит 11), но снимки маршрутов уже запущенных заказов остались со сплит-
-- шаблоном 02: параллельная группа {03 КИПЕРКА, 0001 ПОДГИБКА НИЗА,
-- 16 РАСПОШИВ РУКАВА} перед ОТК. Швеи физически закрывали 11 вместо 03,
-- `issueToEmployee` их пропускал (операции нет в маршруте и она не была
-- заместителем → `evaluateRouteOrder` возвращает `none` и не enforce'ит),
-- а AND-гейт перед ОТК валил скан с `PASSPORT_PARALLEL_GROUP_INCOMPLETE`.
-- Тот же класс инцидента, что и 20260529 (generic РАСПОШИВ 04 вместо сплита),
-- но там его лечили backfill-ом событий; здесь правильнее правило замены —
-- окантовка и киперка это ДВЕ ТЕХНОЛОГИИ ОДНОЙ позиции маршрута (обработка
-- плечевых швов и горловины), а не «недоделанная работа».
--
-- Почему это безопасно для сделки: у 03 и 11 одинаковая ставка (19.23 ₽),
-- и ни на одном паспорте они не встречаются вместе — значит substitute-credit
-- в `EarningsService` (амаунт заместителя минус уже начисленное за
-- замещаемые операции) везде даёт priorSum = 0, то есть полную оплату.
--
-- Почему это не ломает сворачивание сплит-распошива: `findCollapsibleGroup`
-- требует ≥2 операций группы с ОБЩИМ `substituteOpId`; у 11 в группе {03,
-- 0001, 16} ровно один «подопечный» (03), поэтому пара {низ, рукав} → 04
-- остаётся единственной сворачиваемой.
--
-- `isReceivingStation` = false: к адаптивному режиму распошива (route-mode.ts)
-- эта пара отношения не имеет.
--
-- Лук-ап по `code` (id-шники на проде и dev разные) — как в
-- `20260729200000_add_operation_substitution`. Идемпотентно: на проде INSERT
-- уже применён руками 28.07.2026, `migrate deploy` доедет сюда без эффекта.
INSERT INTO "OperationSubstitution" ("id", "satisfiesOpId", "substituteOpId", "isReceivingStation", "createdAt")
SELECT
  'osub_' || substring(md5(sat.id || ':' || sub.id) for 24),
  sat.id,
  sub.id,
  false,
  CURRENT_TIMESTAMP
FROM (VALUES
  ('03', '11')  -- КИПЕРКА ФУТБОЛКА ← ОКАНТОВКА ПЛЕЧЕВЫХ И ГОРЛОВИНЫ
) AS pair(satisfies_code, substitute_code)
JOIN "Operation" sat ON sat.code = pair.satisfies_code
JOIN "Operation" sub ON sub.code = pair.substitute_code
ON CONFLICT ("satisfiesOpId", "substituteOpId") DO NOTHING;
