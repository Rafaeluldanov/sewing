-- Рубильник строгости гейта «работа мимо маршрута»
-- (`CompanySettings.offRouteWorkPolicy`).
--
-- Контекст. Шесть инцидентов одного класса с 13.05.2026: швея берёт
-- паспорт на операцию, которой нет в маршруте заказа, а
-- `PassportsService.evaluateRouteOrder` в этом случае возвращает пустой
-- результат и отключает проверку ЦЕЛИКОМ. Работа принимается молча,
-- сделка начисляется, партия шьётся до конца — и упирается только в
-- AND-гейт перед ОТК, недели спустя, сразу десятками паспортов
-- (28.07.2026 — 70 паспортов в 8 заказах, лаг обнаружения 27 дней).
--
-- Лечится это только отказом в момент взятия операции. Но жёсткий отказ
-- без возможности откатить = остановка цеха: любая нештатная ситуация
-- упирается в 409, и фичу выключат насовсем, второй раз её никто не
-- включит. Поэтому строгость — настройка, которая меняется без релиза.
--
-- Default `WARN`, а НЕ `BLOCK`: после миграции поведение цеха не
-- меняется (никто ничего не перестаёт мочь), но каждый случай начинает
-- писаться в лог и аудит. Переключение в `BLOCK` — отдельное решение
-- владельца по накопленной статистике, и только после того, как:
--   1) разобраны 12 активных шаблонов, у которых швейная операция лежит
--      в архиве (иначе 28 заказов не смогут стартовать);
--   2) заведён наряд-допуск мастера — легальный обход для нештатных
--      ситуаций.
--
-- `OFF` оставлен как аварийный выход: вернуть ровно поведение до
-- 28.07.2026, если что-то пойдёт не так.

-- CreateEnum
CREATE TYPE "OffRouteWorkPolicy" AS ENUM ('OFF', 'WARN', 'BLOCK');

-- AlterTable
ALTER TABLE "CompanySettings"
  ADD COLUMN "offRouteWorkPolicy" "OffRouteWorkPolicy" NOT NULL DEFAULT 'WARN';
