-- ⛔ `READY` без закрытого заказа не бывает — ERP читает только `READY`, поэтому недошитый
-- выпуск к ней не уедет. Номер у документа, заведённого заранее, несёт дату ФОРМИРОВАНИЯ, а не
-- закрытия: другой даты в тот момент ещё нет.

ALTER TABLE "ProductionDocument" ALTER COLUMN "closedAt" DROP NOT NULL;
