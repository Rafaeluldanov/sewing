-- вводит «Упаковок» / «Шт/упак» / «Цена за упаковку», но в БД строка
-- остаётся поштучно (purchaseQty = упаковок × packSize, quotedPrice =
-- цена за упаковку ÷ packSize). Отдельная колонка packSize хранит
-- «штук в упаковке», чтобы при перезагрузке восстановить разбивку.
-- Nullable: у всех прочих строк остаётся NULL, поведение не меняется.
ALTER TABLE "WorkshopNeed" ADD COLUMN "packSize" DECIMAL(14,4);
