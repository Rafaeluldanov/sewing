-- Новый статус задания на печать: `SENT` — агент атомарно «захватил»
-- job и печатает его прямо сейчас (PENDING → SENT на поллинге). Пока
-- job в этом статусе, его не получит ни повторный поллинг того же
-- агента, ни второй агент на том же принтере — это защита от повторной
-- физической печати одного паспорта.
--
-- ВАЖНО: `ALTER TYPE ... ADD VALUE` нельзя выполнять внутри транзакции,
-- поэтому расширение enum вынесено в ОТДЕЛЬНУЮ «raw»-миграцию с одним
-- `ALTER TYPE` (см. `20260818100000_order_status_sample_production`).
-- Само использование `SENT` (в колонках/индексах) — в следующей
-- миграции `20260901100010_printjob_idempotency_and_claim`.

ALTER TYPE "PrintJobStatus" ADD VALUE IF NOT EXISTS 'SENT';
