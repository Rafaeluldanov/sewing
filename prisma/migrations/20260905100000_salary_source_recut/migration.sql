-- Новый источник строки ведомости: `RECUT` — почасовая ДОПЛАТА сверх
-- смены за «подкрой» (докрой недостающих/бракованных деталей,
-- `model RecutSession`). Отдельная строка `SalaryEntry(source=RECUT)`,
-- время подкроя при этом остаётся и в `SHIFT_DAY` (не вычитается).
--
-- ВАЖНО: `ALTER TYPE ... ADD VALUE` нельзя выполнять внутри транзакции,
-- поэтому расширение enum вынесено в ОТДЕЛЬНУЮ «raw»-миграцию с одним
-- `ALTER TYPE` (тот же приём, что и `20260901100000_printjob_add_sent_status`).
-- Само использование `RECUT` — в рантайме (`SalaryService.syncDailyRecut`);
-- в схеме/индексах оно нигде не участвует, поэтому отдельной «usage»-
-- миграции не требуется.

ALTER TYPE "SalaryEntrySource" ADD VALUE IF NOT EXISTS 'RECUT';
