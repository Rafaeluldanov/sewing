-- Этап «Архив справочников» — заявки конструктору
-- (`/admin/constructor-tasks`, контракт `@sewing/shared/archive`).
--
-- Мягкая архивация заявки: запись скрывается из активного списка
-- (`archivedAt != NULL`), уезжает во вкладку «Архив», откуда её можно
-- вернуть (обнулить поле) или удалить безвозвратно вместе со строками
-- размеров и вложениями (оба уходят каскадом по существующим FK).
--
-- Почему отдельное поле, а не статус: `status` описывает ход работы КБ
-- (NEW → IN_PROGRESS → PENDING_ACCEPT → DONE/CANCELLED). «Убрать с глаз»
-- отработанную заявку нужно, не переписывая её историю.
--
-- Аддитивно: колонка nullable, дефолта нет — существующие заявки
-- остаются активными.
ALTER TABLE "ConstructorTask" ADD COLUMN "archivedAt" TIMESTAMP(3);

-- Индекс под фильтр «активные / архив» в списке заявок.
CREATE INDEX "ConstructorTask_archivedAt_idx" ON "ConstructorTask"("archivedAt");
