-- Фича «Показать пароль сотрудника в карточке».
--
-- До сих пор PIN хранился ТОЛЬКО как bcrypt-хеш (`Employee.pinHash`),
-- поэтому «посмотреть пароль» было невозможно математически, а забытый
-- PIN лечился исключительно сбросом. Менеджеру же нужно уметь
-- продиктовать человеку его код, не меняя код.
--
-- Добавляем вторую, ОБРАТИМУЮ копию: AES-256-GCM на мастер-ключе из env
-- `INTEGRATION_SECRET_KEY` (тот же crypto-util, что шифрует пароль
-- интеграции upgifts — `apps/api/src/modules/integrations/secret-box.ts`,
-- формат `v1.<base64(iv‖tag‖ciphertext)>`).
--
-- Вход НЕ переезжает на эту колонку: `AuthService.login` по-прежнему
-- сверяет bcrypt-хеш, `pinHash` остаётся NOT NULL. Колонка нужна ровно
-- для показа в блоке «Доступ» карточки `/admin/employees/[id]`.
--
-- Колонка nullable и без DEFAULT, бэкфилла нет и быть не может: у уже
-- заведённых сотрудников открытого PIN'а не существует ни в каком виде.
-- NULL = «показать нечего, можно только задать заново» — ровно прежнее
-- поведение карточки.

ALTER TABLE "Employee" ADD COLUMN "pinEnc" TEXT;
