-- Фича «Состав заказа — единственная истина для закупки».
--
-- Потребность цеха у category-driven заказа считается по параметрам
-- лекала, а спецификация заказа (`OrderMaterialRequirement`) собиралась
-- ТОЛЬКО из строк техкарты. Параметр, под который строки техкарты нет
-- (типовой случай — роль RIB: «Рибана»/«Кашкорсе» ведутся в
-- номенклатуре), не попадал в спецификацию вовсе: в расцветке его не
-- видно, убрать из заказа нечем — а в закупку он шёл. Правка менеджера
-- переставала быть конечной.
--
-- Теперь такие параметры материализуются в спецификацию наравне со
-- строками техкарты, а их удаление гасит потребность.
--
-- Колонка — отметка «снимок собран новым правилом». Отличить «строку
-- удалили» от «строки тут никогда не было» по самим данным нельзя:
-- удали менеджер все посеянные строки, признак исчез бы вместе с ними
-- и материал вернулся бы на первом же пересчёте.
--
-- Nullable, без DEFAULT и без бэкфилла — сознательно: исторические
-- заказы остаются с NULL, их снимок собран старым правилом, гейт к ним
-- не применяется. Иначе рибана молча исчезла бы из закупки уже
-- посчитанного заказа.

ALTER TABLE "Order" ADD COLUMN "specPatternParamsSeededAt" TIMESTAMP(3);
