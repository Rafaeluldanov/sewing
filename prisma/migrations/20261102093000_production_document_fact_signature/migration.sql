--
-- Документ собирается сам, но «сам» не значит «на каждый чих»: полный пересчёт тянет разноску
-- оклада по окну производства — это дорого. Отпечаток дешёвых агрегатов (списания, возвраты,
-- начисления, подкрой, прочие расходы, количество событий по паспортам) позволяет при чтении
-- за копейки понять, изменилось ли что-нибудь, и пересобирать документ ТОЛЬКО когда изменилось.
--
-- Без него сформированный документ не замечал позднего факта: пересборка шла только у
-- формирующихся, и списание, проведённое задним числом, расходилось с цехом молча.

