-- 09.06.2026 Прод: добавление категории «Шопер» падало с
-- PATTERN_CATEGORY_SLUG_TAKEN.
--
-- Причина: категория «Фартук» (id cmq5au03f035eyswu6eimlokg) держала
-- slug `shoper` — очевидно, её сперва завели как «Шопер», потом
-- переименовали в «Фартук», не поправив slug (slug руками не меняется
-- при переименовании). Авто-slug для нового «Шопер» = `shoper`
-- (ш→sh, о→o, п→p, е→e, р→r) → коллизия по уникальному индексу slug.
--
-- Фикс: вернуть «Фартук» корректный slug `fartuk` (свободен, на
-- категорию не ссылались ни лекала, ни техкарты; slug — не FK).
-- После этого `shoper` освобождается и «Шопер» создаётся штатно.

UPDATE "PatternCategory"
SET slug = 'fartuk', "updatedAt" = now()
WHERE id = 'cmq5au03f035eyswu6eimlokg'
  AND name = 'Фартук'
  AND slug = 'shoper';
