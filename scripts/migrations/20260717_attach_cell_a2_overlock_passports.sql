-- 2026-07-17 · PROD data-fix
--
-- Контекст. Пять паспортов заказа O-20260716-… прошли МИМО ячеек:
-- помощник раскройщика не выполнил `place` (нет события CELL_PLACED,
-- `currentCellId = NULL`), а оверлокщик Марипов Алмазбек сразу забрал
-- крой себе (`ISSUED_TO_EMPLOYEE`, статус IN_PROGRESS, шаг маршрута 1).
--
-- Задача от цеха: оставить паспорта НА ОВЕРЛОКЕ (не снимать с Марипова),
-- но задним числом привязать их к существующей свободной ячейке A2 —
-- чисто как метку на уровне паспорта.
--
-- ВНИМАНИЕ. Это сознательно НЕконсистентное состояние (паспорт
-- одновременно `currentEmployeeId != NULL` и `currentCellId != NULL`),
-- которого штатный флоу избегает: и `PassportsService.place`, и
-- `MasterActionsService.returnToCell` обнуляют одно при выставлении
-- другого. Поэтому правка только прямым UPDATE. Реестр полуфабриката
-- (WorkInProgressMovement / CellContent) СОЗНАТЕЛЬНО не наполняем —
-- привязка нужна лишь как метка ячейки, не как складской остаток.
-- Событие CELL_PLACED тоже не пишем (его в истории не было).
--
-- При следующем штатном issue/scan на оверлоке `currentCellId` будет
-- снят системой — метка живёт, пока паспорта физически не двинулись.
--
-- Применено на проде (sewing-prod-db-1 / myapp) 2026-07-17 → UPDATE 5.

UPDATE "Passport"
SET "currentCellId" = (SELECT id FROM "Cell" WHERE code = 'A2'),
    "updatedAt"     = now()
WHERE number IN (
  'P-20260716-0011',
  'P-20260716-0012',
  'P-20260716-0013',
  'P-20260716-0014',
  'P-20260716-0015'
);
