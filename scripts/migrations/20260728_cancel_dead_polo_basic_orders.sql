-- 2026-07-28 data-fix (prod). ПРИМЕНЕНО.
--
-- Отмена двух мёртвых заказов, найденных при разборе инцидента «работа мимо
-- маршрута»: O-20260615-0004 (Поло Basic) и O-20260615-0005 (Жилетка Basic).
--
-- Почему они стояли. У ОБОИХ все швейные операции маршрута заархивированы при
-- живых заказах — швея физически не может их выбрать (список операций берётся
-- из `EquipmentOperation` станка, архивные туда не попадают):
--   O-20260615-0004: 017 ПРЯМОСТРОЧКА Поло Basic, PL_BASIC_SEW ОВЕРЛОК Поло Basic
--                    (эта ещё и не висит НИ НА ОДНОМ станке), 016 РАСПОШИВ Поло Basic
--   O-20260615-0005: 019 ПРЯМОСТРОЧКА Жилетка Basic; плюс маршрут обрезан до двух
--                    шагов — нет ни ОТК, ни ВТО, ни упаковки
-- Это ровно та дыра, которую описывает п. 3.5 плана: в
-- `OperationsService` (apps/api/src/modules/operations/operations.service.ts)
-- на месте проверки «операция стоит в живом заказе» — пустая заглушка, архивация
-- не блокируется.
--
-- Заказы стоят с 30.06.2026 без единого события, и никто об этом не знал.
-- Владелец решил: изделия сняты с производства, заказы не шьём.
--
-- `cancel()` в OrderService — чистая смена статуса без каскадов и очисток
-- (см. orders.service.ts, ~строка 3563: комментарий «Snapshot-поля себестоимости
-- НЕ очищаем — остаются как историческое состояние»). Поэтому здесь ровно тот же
-- UPDATE, что сделала бы кнопка «Отменить» в карточке заказа. Паспорта остаются
-- как есть (32 IN_PROGRESS + 40 CREATED), начисления не реверсируются — работа
-- физически была выполнена.
--
-- ⚠️ ОТКРЫТЫЙ ВОПРОС, НЕ ЗАКРЫТ ЭТИМ ПАТЧОМ: недоплата швеям по O-20260615-0004.
-- Работа закрывалась на мусорных 1 ₽-операциях вместо маршрутных:
--   400 шт на `098642 ОВЕРЛОК` (1.00 ₽) вместо PL_BASIC_SEW (62.50 ₽)  → 400 ₽ вместо 25 000 ₽
--   600 шт на `STRAIGHT_STEECH`  (1.00 ₽) вместо 017          (112.50 ₽) → 600 ₽ вместо 67 500 ₽
--   200 шт на `02 ОВЕРЛОК ФУТБОЛКА` (50.00 ₽) вместо PL_BASIC_SEW (62.50 ₽) → недобор 2 500 ₽
-- Разрыв ≈ 94 000 ₽. Доначисление НЕ делалось: сами эталонные ставки вызывают
-- сомнения (019 ПРЯМОСТРОЧКА Жилетка Basic = 1053.00 ₽/шт — похоже на опечатку
-- в справочнике). Сверить ставки с технологом, затем решать по доначислению.
--
-- ПРИМЕНЕНО НА ПРОДЕ 2026-07-28. Результат: UPDATE 2.

BEGIN;

UPDATE "Order"
   SET status = 'CANCELLED'
 WHERE number IN ('O-20260615-0004', 'O-20260615-0005')
   AND status NOT IN ('DONE', 'CANCELLED');

COMMIT;
