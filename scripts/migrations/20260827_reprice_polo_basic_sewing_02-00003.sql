-- 2026-08-27 data-fix (prod)
-- Заказ 02-00003 «Поло Basic (Сакура)», 300 шт, IN_PRODUCTION.
-- Пересчёт уже начисленных сделок по швейным операциям с плейсхолдера
-- 1,00 ₽/шт на согласованные владельцем расценки Поло Basic.
--
-- ЧТО ПРОИЗОШЛО.
-- Справочные `FIXED 1.00 ₽` у `STRAIGHT_STEECH ПРЯМОСТРОЧКА` и
-- `098642 ОВЕРЛОК` — это ПЛЕЙСХОЛДЕР: реальная цена шага живёт в
-- `OrderRouteStep.rateOverride`. В базе сосуществуют две конвенции:
--   A — «весь пошив одной строкой»: `ПРЯМОСТРОЧКА` несёт цену всего
--       пошива за штуку (572 / 615.40 / 769 / 898 ₽), остальные швейные
--       шаги НАМЕРЕННО стоят 1 ₽ (деньги уже в первой строке). Так
--       устроены 02-00001, -00008…-00011, -00014, -00016…-00019, -00024.
--   B — «маршрут по операциям»: шаги идут по справочным расценкам
--       (петля 6.25, пуговица 6.25, распошив 25.64), а главная швейная
--       операция осталась на плейсхолдере — то есть основной пошив не
--       оплачен вовсе. Так устроены 02-00003, -00007, -00015.
-- 02-00003 — конвенция B: 302 изделия прошли прямострочку за 302,00 ₽ и
-- оверлок за 302,00 ₽.
--
-- РАСЦЕНКИ. Согласованы владельцем 27.08 по архивированным выделенным
-- операциям Поло Basic: `017 ПРЯМОСТРОЧКА Поло Basic` = 112.50 ₽/шт,
-- `PL_BASIC_SEW ОВЕРЛОК Поло Basic` = 62.50 ₽/шт.
--
-- ПОСЛЕДСТВИЯ ДО ПРАВКИ.
--   * ПРЯМОСТРОЧКА: Талайбекова Жанара 186 шт / 186,00 ₽,
--     Джалилова Айзада 116 шт / 116,00 ₽.
--   * ОВЕРЛОК:      Марипов Алмазбек 302 шт / 302,00 ₽.
--   * Все 38 сделок в PENDING_RELEASE, в `PayrollPayoutLine` не ушли
--     (проверено: 0 строк) — никому по рублю не выплачено.
--
-- ПРАВКА. `OperationEntry` — снимок начисления, задним числом его
-- пересчитывает только ручная правка (ср. `EarningsService`:
-- `reconcileToQtyGood` выравнивает КОЛИЧЕСТВО по своей же сохранённой
-- расценке и цену не трогает). Меняем `ratePerUnit` и `amount`,
-- `qty` не трогаем.
--   ПРЯМОСТРОЧКА  19 строк: 302 шт   302,00 →  33 975,00 ₽
--   ОВЕРЛОК       19 строк: 302 шт   302,00 →  18 875,00 ₽
--   ИТОГО                   604,00 → 52 850,00 ₽ (доплата 52 246,00 ₽)
--
-- НЕ ВХОДИТ В ЭТОТ SQL: сам `OrderRouteStep.rateOverride` на четырёх
-- шагах (02-00003 ×2, 02-00007 ×1, 02-00015 ×1). Его правит ТОЛЬКО
-- `OrdersService.updateRouteOverrides` (карточка заказа → «Редактировать
-- маршрут заказа» → «Сохранить всё»): вместе с записью он пересчитывает
-- плановый снимок `Order.operationCostPlanRub` / `operationTimePlanSec`.
-- Кнопка «Пересчитать план операций» здесь не поможет —
-- `recalculateOperationPlan` запрещён в CALCULATION_DONE и вне
-- DRAFT/CALCULATION, а все три заказа именно там. Поставить расценку
-- SQL-ом = оставить план навсегда со старой ценой.
--
-- 02-00001 НЕ ТРОГАЕМ: там 1 ₽ на оверлоке — конвенция A, так и задумано
-- (пошив оплачен строкой прямострочки 615,40 ₽). Подтверждено владельцем.
--
-- order 02-00003      = cms49wxw... (см. подзапрос по number)
-- op STRAIGHT_STEECH  = ПРЯМОСТРОЧКА, FIXED 1.00 (плейсхолдер)
-- op 098642           = ОВЕРЛОК,      FIXED 1.00 (плейсхолдер)

BEGIN;

WITH target AS (
  SELECT oe.id, op.code
    FROM "OperationEntry" oe
    JOIN "Passport" p  ON p.id = oe."passportId"
    JOIN "Order"    o  ON o.id = p."orderId"
    JOIN "Operation" op ON op.id = oe."operationId"
   WHERE o.number = '02-00003'
     AND op.code IN ('STRAIGHT_STEECH','098642')
     AND oe.status = 'PENDING_RELEASE'
     AND oe."ratePerUnit" = 1.00
     -- страховка: выплаченную строку не трогаем ни при каких условиях
     AND NOT EXISTS (SELECT 1 FROM "PayrollPayoutLine" pl
                      WHERE pl."operationEntryId" = oe.id)
)
, upd AS (
  UPDATE "OperationEntry" oe
     SET "ratePerUnit" = CASE t.code WHEN 'STRAIGHT_STEECH' THEN 112.50
                                     ELSE 62.50 END,
         amount        = oe.qty * CASE t.code WHEN 'STRAIGHT_STEECH' THEN 112.50
                                              ELSE 62.50 END
    FROM target t
   WHERE oe.id = t.id
  RETURNING t.code, oe.qty, oe.amount
)
SELECT code,
       count(*)    AS entries,   -- ожидаем 19 / 19
       sum(qty)    AS qty,       -- ожидаем 302 / 302
       sum(amount) AS amount     -- ожидаем 33975.00 / 18875.00
  FROM upd GROUP BY code ORDER BY code;

-- Смета и плановая себестоимость посчитаны по старой цене: помечаем
-- устаревшими, чтобы менеджер увидел плашку «пересчитайте». Флаг
-- ставится ровно так же, как это делает `OrderCostEstimatesService`
-- (`costEstimateStaleAt` + текстовая причина).
UPDATE "Order"
   SET "costEstimateStaleAt"     = now(),
       "costEstimateStaleReason" = 'Расценки пошива Поло Basic подняты с плейсхолдера 1 ₽ (прямострочка 112,50 ₽/шт, оверлок 62,50 ₽/шт) — пересчитайте смету.'
 WHERE number IN ('02-00003','02-00007','02-00015');

COMMIT;
