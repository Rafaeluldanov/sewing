-- 2026-07-28 data-fix (prod). ПРИМЕНЕНО.
--
-- Снятие мусорных операций-двойников со ставкой 1.00 ₽ с оборудования.
--
-- Контекст. Швея выбирает операцию из списка своего СТАНКА
-- (`EquipmentOperation`, см. apps/api/src/modules/shifts/shifts.service.ts) —
-- маршрут заказа в этом выборе не участвует вообще. Пока на станке рядом с
-- настоящей операцией висит одноимённый дубль со ставкой 1 ₽, промах — вопрос
-- времени, и он бьёт дважды: работа уходит мимо маршрута (заказ залипает на
-- гейте ОТК) и швея получает 1 ₽/шт вместо реальной расценки.
--
-- Снято:
--   56789  РАСПОШИВ (1.00 ₽) — 4 связки (rasposhiv, -2, -3, -4)
--   098642 ОВЕРЛОК  (1.00 ₽) — 8 связок (overlok, -2 … -8)
--   ИТОГО 12 связок.
--
-- Обе безопасны: ни одна не стоит ни в одном шаблоне маршрута и ни в одном
-- снимке маршрута заказа, активных смен на них нет. На КАЖДОМ затронутом станке
-- остаётся настоящая операция — проверено до и после:
--   overlok*    → 02 ОВЕРЛОК ФУТБОЛКА (BY_SIZE)
--   rasposhiv*  → 04 РАСПОШИВ ФУТБОЛКА (25.64), 16 РАСПОШИВ РУКАВА (12.82),
--                 0001 ПОДГИБКА НИЗА, COVERLOCK_NECK РАСПОШИВ ГОРЛОВИНА (16.25)
--
-- НЕ ТРОНУТА `STRAIGHT_STEECH ПРЯМОСТРОЧКА` (тоже 1.00 ₽, 12 станков), хотя
-- изначально числилась в том же списке: она стоит в 2 шаблонах маршрута
-- («Жилетка Мистраль», «Худи РСВ») и в 4 снимках маршрутов заказов, и на ней
-- открыта смена. Это НАСТОЯЩАЯ операция с ошибочной ставкой — ей нужна
-- корректная расценка, а не снятие со станков. Оставлено владельцу.
--
-- Сами операции 56789/098642 НЕ архивированы: у 098642 48 исторических событий,
-- архивация сделала бы их ссылками на архивную операцию. Снятие со станков —
-- минимальное действие, которое перекрывает канал промаха, не трогая историю.
--
-- ПРИМЕНЕНО НА ПРОДЕ 2026-07-28. Результат: DELETE 12.

BEGIN;

-- Страховка: не снимаем, если на операции есть активная смена.
DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM "ShiftSession" s
  JOIN "Operation" o ON o.id = s."operationId"
  WHERE s."endedAt" IS NULL AND o.code IN ('56789','098642');
  IF n > 0 THEN RAISE EXCEPTION 'Есть % активных смен на снимаемых операциях — отмена', n; END IF;
END $$;

DELETE FROM "EquipmentOperation" eo
USING "Operation" o
WHERE o.id = eo."operationId" AND o.code IN ('56789','098642');

COMMIT;

