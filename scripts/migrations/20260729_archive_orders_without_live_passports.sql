-- 2026-07-29 data-fix (prod). ПРИМЕНЕНО.
--
-- Массовая архивация заказов по решению владельца: оставить активными
-- только 02-00001, O-20260721-0001 и O-20260716-0001, ОСТАЛЬНЫЕ убрать —
-- но НЕ трогая заказы с живыми паспортами (уточнение владельца в ходе
-- работы: «активные паспорта мы не трогаем»).
--
-- «Архив» заказа в этой системе — это `status = CANCELLED`: отдельного
-- поля архива у `Order` нет, а `OrdersService.cancel()` прямо описывает
-- отмену как soft-архив («Snapshot-поля себестоимости НЕ очищаем —
-- остаются как историческое состояние»). `needsArchivedAt` к заказу
-- отношения не имеет — это архив РАСЧЁТОВ ЦЕХА.
--
-- Отменено 53 заказа: 21 CALCULATION_DONE, 13 CALCULATION, 10 DRAFT,
-- 9 IN_PRODUCTION (у последних все паспорта уже упакованы либо отменены).
--
-- Кого НЕ трогали и почему:
--   * 3 заказа из списка владельца;
--   * 14 заказов с живыми паспортами — 499 паспортов / 7 358 изделий;
--   * 2 заказа в статусе DONE — домен запрещает их отменять
--     (`cancel()` бросает «Заказ уже завершён или отменён»), и они уже
--     закрыты;
--   * 7 заказов, отменённых ранее.
--
-- Почему это безопасно для денег: `cancel()` — чистая смена статуса без
-- каскадов. Проверено отдельно, что ни `PayrollService`, ни
-- `EarningsService` не фильтруют начисления по статусу заказа, поэтому
-- 291 808 ₽ невыплаченной сделки (`PENDING_RELEASE`) на паспортах этих
-- заказов остаются доступными к выплате. Паспорта, события и история
-- сохраняются полностью.
--
-- ⚠️ Обратите внимание: 9 отменённых заказов были в статусе
-- IN_PRODUCTION с полностью упакованными паспортами. По-хорошему их
-- следовало довести до DONE, а не отменять, — но по прямому решению
-- владельца они убраны в архив вместе с остальными.
--
-- ПРИМЕНЕНО НА ПРОДЕ 2026-07-29. Результат: UPDATE 53.
-- Контроль после применения: ни один из 53 не держал живого паспорта
-- (73 живых паспорта в CANCELLED — из заказов, отменённых РАНЕЕ:
-- O-20260615-0004/-0005 и O-20260616-0002).

BEGIN;

UPDATE "Order" o
   SET status = 'CANCELLED'
 WHERE o.number NOT IN ('02-00001', 'O-20260721-0001', 'O-20260716-0001')
   AND o.status NOT IN ('CANCELLED', 'DONE')
   AND NOT EXISTS (
     SELECT 1 FROM "Passport" p
      WHERE p."orderId" = o.id
        AND p.status NOT IN ('PACKED', 'CANCELLED')
   );

COMMIT;

